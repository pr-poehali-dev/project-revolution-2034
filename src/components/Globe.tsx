// Более точная маска суши — используем географические данные
function isLand(lat: number, lon: number): boolean {
  // Северная Америка
  if (lat > 25 && lat < 72 && lon > -168 && lon < -52) {
    if (lat > 60 && lon < -130) return true;
    if (lat > 50 && lon < -55) return true;
    if (lat > 40 && lon > -125 && lon < -60) return true;
    if (lat > 25 && lon > -120 && lon < -85) return true;
    if (lat > 60 && lon > -140 && lon < -60) return true;
    if (lat < 72 && lat > 45 && lon > -95 && lon < -55) return true;
    return lat > 30 && lat < 70 && lon > -130 && lon < -60;
  }
  // Гренландия
  if (lat > 60 && lat < 84 && lon > -58 && lon < -17) return true;
  // Центральная Америка
  if (lat > 7 && lat < 25 && lon > -92 && lon < -60) return true;
  // Южная Америка
  if (lat > -56 && lat < 12 && lon > -82 && lon < -34) {
    if (lat > -20 && lon > -82 && lon < -34) return true;
    if (lat > -56 && lat < -20 && lon > -75 && lon < -40) return true;
    return true;
  }
  // Западная Европа
  if (lat > 36 && lat < 72 && lon > -10 && lon < 35) {
    if (lat > 55 && lon > -5 && lon < 30) return true;
    if (lat > 44 && lat < 58 && lon > -5 && lon < 25) return true;
    if (lat > 36 && lat < 48 && lon > -5 && lon < 20) return true;
    return true;
  }
  // Скандинавия
  if (lat > 55 && lat < 72 && lon > 4 && lon < 32) return true;
  // Британские острова
  if (lat > 50 && lat < 60 && lon > -8 && lon < 2) return true;
  // Россия + Сибирь
  if (lat > 50 && lat < 78 && lon > 28 && lon < 190) return true;
  if (lat > 42 && lat < 55 && lon > 28 && lon < 140) return true;
  // Казахстан + Средняя Азия
  if (lat > 37 && lat < 55 && lon > 52 && lon < 90) return true;
  // Ближний Восток
  if (lat > 12 && lat < 42 && lon > 26 && lon < 62) return true;
  // Индия
  if (lat > 8 && lat < 35 && lon > 68 && lon < 92) return true;
  // Китай + ЮВА
  if (lat > 18 && lat < 50 && lon > 90 && lon < 135) return true;
  if (lat > 0 && lat < 22 && lon > 100 && lon < 122) return true;
  // Япония
  if (lat > 30 && lat < 46 && lon > 129 && lon < 146) return true;
  // Африка
  if (lat > -35 && lat < 37 && lon > -18 && lon < 52) {
    if (lat > 15 && lon > -18 && lon < 52) return true;
    if (lat > -5 && lat < 15 && lon > -18 && lon < 50) return true;
    if (lat > -35 && lat < -5 && lon > 10 && lon < 42) return true;
    return false;
  }
  // Мадагаскар
  if (lat > -26 && lat < -12 && lon > 43 && lon < 51) return true;
  // Австралия
  if (lat > -40 && lat < -10 && lon > 113 && lon < 155) return true;
  // Новая Зеландия
  if (lat > -47 && lat < -34 && lon > 166 && lon < 178) return true;
  // Исландия
  if (lat > 63 && lat < 67 && lon > -24 && lon < -13) return true;
  // Антарктида
  if (lat < -70) return true;

  return false;
}

function toXYZ(lat: number, lon: number, r: number): THREE.Vector3 {
  const phi = (90 - lat) * (Math.PI / 180);
  const theta = (lon + 180) * (Math.PI / 180);
  return new THREE.Vector3(
    -r * Math.sin(phi) * Math.cos(theta),
    r * Math.cos(phi),
    r * Math.sin(phi) * Math.sin(theta)
  );
}

function GlobeMesh() {
  const groupRef = useRef<THREE.Group>(null);

  const dotPoints = useMemo(() => {
    const r = 2.21;
    const pts: THREE.Vector3[] = [];
    const step = 3.5; // градусов между точками

    for (let lat = -90; lat <= 90; lat += step) {
      for (let lon = -180; lon < 180; lon += step) {
        if (isLand(lat, lon)) {
          pts.push(toXYZ(lat, lon, r));
        }
      }
    }
    return new THREE.BufferGeometry().setFromPoints(pts);
  }, []);

  useFrame((_, delta) => {
    if (groupRef.current) groupRef.current.rotation.y += delta * 0.1;
  });

  return (
    <group ref={groupRef}>
      <mesh>
        <sphereGeometry args={[2.2, 64, 64]} />
        <meshBasicMaterial color="#000000" transparent opacity={0.08} />
      </mesh>
      <points geometry={dotPoints}>
        <pointsMaterial
          color="#ffffff"
          size={0.06}
          transparent
          opacity={0.55}
          sizeAttenuation
        />
      </points>
    </group>
  );
}

